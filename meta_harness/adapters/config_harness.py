"""Config harness: turns a production agent's config into a searchable harness.

The user's entrypoint is `module:function(task, config, model) -> dict` and runs their real agent
(LangGraph graph, OpenAI Agents SDK agent, Claude Agent SDK client, a custom service) with
`config`. `init_seed` scaffolds a seed directory:

    seed_dir/harness.py    generated from TEMPLATE; never edited by hand or by the proposer
    seed_dir/config.json   the knobs: prompts, tool descriptions, few-shot, thresholds, k, memory
    seed_dir/schema.json   types, enums, bounds, max lengths, required and frozen keys

`harness.run(task, model)` loads its sibling `config.json` and calls the entrypoint. A search copies
only `harness.py` into each candidate directory, so the generated file also carries config.json
verbatim between `# BEGIN CONFIG` and `# END CONFIG`; that block IS config.json for a candidate
and is the only bytes a proposer may change. When a sibling config.json exists it must equal
the block (`sync_seed` rewrites the block after a hand edit of config.json).

`validate_candidate(candidate_dir, seed_dir, schema)` is the config-only gate: it refuses any
change to harness.py outside the config block and any config value that violates the schema.
"""

from __future__ import annotations

import ast
import json
import re
import shutil
from pathlib import Path
from typing import Any, Mapping

from .schema import check_schema, validate_config

GENERATOR = "meta-harness adapt init"
PACKAGE_ROOT = Path(__file__).resolve().parents[2]  # the directory holding the meta_harness package
CONFIG_PLACEHOLDER = "<CONFIG>"

TEMPLATE = '''"""Config harness generated by {generator}. Do not edit this file.

The proposer edits only the JSON between BEGIN CONFIG and END CONFIG (it is config.json);
any other change is rejected by the agent_config gate.
"""

import importlib
import json
import sys
from pathlib import Path

ENTRYPOINT = {entrypoint!r}
ENTRY_PATH = {entry_path!r}
ENTRY_BASE = {entry_base!r}

SCHEMA_JSON = r\'\'\'
{schema}
\'\'\'

# BEGIN CONFIG
CONFIG_JSON = r\'\'\'
{config}
\'\'\'
# END CONFIG


def _entry_dir():
    if ENTRY_BASE == "package":
        import meta_harness
        return Path(meta_harness.__file__).resolve().parents[1] / ENTRY_PATH
    return Path(ENTRY_PATH)


def load_config():
    sibling = Path(__file__).resolve().with_name("config.json")
    if sibling.is_file():
        return json.loads(sibling.read_text(encoding="utf-8"))
    return json.loads(CONFIG_JSON)


def load_entrypoint():
    module_name, _, function = ENTRYPOINT.partition(":")
    folder = str(_entry_dir())
    if folder not in sys.path:
        sys.path.insert(0, folder)
    return getattr(importlib.import_module(module_name), function)


class Harness:
    def __init__(self):
        self.config = load_config()
        self.entry = load_entrypoint()

    def run(self, task, model, trace=None):
        result = self.entry(dict(task), json.loads(json.dumps(self.config)), model)
        if trace is not None and hasattr(trace, "event"):
            trace.event("adapter_call", {{"entrypoint": ENTRYPOINT}})
        if isinstance(result, dict):
            return result
        return {{"output": result}}
'''

_CONFIG_RE = re.compile(r"# BEGIN CONFIG\nCONFIG_JSON = r'''\n(.*?)\n'''\n# END CONFIG\n", re.DOTALL)
_SCHEMA_RE = re.compile(r"\nSCHEMA_JSON = r'''\n(.*?)\n'''\n", re.DOTALL)
_PARAM_RE = {name: re.compile(rf"^{name} = (.+)$", re.MULTILINE)
             for name in ("ENTRYPOINT", "ENTRY_PATH", "ENTRY_BASE")}


class ConfigHarnessError(ValueError):
    """A candidate or seed that the config gate refuses."""


def _dump(value: Any) -> str:
    text = json.dumps(value, indent=2, ensure_ascii=False)
    if "'''" in text:
        raise ConfigHarnessError("config and schema text may not contain three single quotes in a row")
    return text


def entry_location(path: Path) -> tuple[str, str]:
    """(ENTRY_PATH, ENTRY_BASE): relative to the package root when inside it (so the generated
    file is the same on every checkout), absolute otherwise."""
    path = Path(path).resolve()
    try:
        return path.relative_to(PACKAGE_ROOT).as_posix(), "package"
    except ValueError:
        return str(path), "absolute"


def render_harness(entrypoint: str, entry_path: str, entry_base: str, schema: Mapping[str, Any],
                   config: Any) -> str:
    if not re.fullmatch(r"[A-Za-z_][\w.]*:[A-Za-z_]\w*", entrypoint or ""):
        raise ConfigHarnessError(f"entrypoint must be module:function, got {entrypoint!r}")
    if entry_base not in ("package", "absolute"):
        raise ConfigHarnessError(f"entry_base must be 'package' or 'absolute', got {entry_base!r}")
    check_schema(schema)
    text = TEMPLATE.format(generator=GENERATOR, entrypoint=entrypoint, entry_path=entry_path,
                           entry_base=entry_base, schema=_dump(schema), config=_dump(config))
    return text


def split_harness(text: str) -> tuple[str, str]:
    """(fixed text with the config block replaced by a placeholder, raw config block)."""
    text = text.replace("\r\n", "\n")
    matches = list(_CONFIG_RE.finditer(text))
    if len(matches) != 1:
        raise ConfigHarnessError("harness.py is not a config harness: it needs exactly one "
                                 "BEGIN CONFIG / END CONFIG block")
    match = matches[0]
    fixed = text[:match.start(1)] + CONFIG_PLACEHOLDER + text[match.end(1):]
    return fixed, match.group(1)


def parse_harness(text: str) -> dict[str, Any]:
    """The parameters of a generated harness: entrypoint, entry_path, entry_base, schema, config,
    fixed (template text with the config placeholder)."""
    fixed, raw_config = split_harness(text)
    try:
        config = json.loads(raw_config)
    except ValueError as exc:
        raise ConfigHarnessError(f"config block is not valid JSON: {exc}") from None
    schema_match = _SCHEMA_RE.search(fixed)
    if schema_match is None:
        raise ConfigHarnessError("harness.py is not a config harness: no SCHEMA_JSON block")
    try:
        schema = json.loads(schema_match.group(1))
    except ValueError as exc:
        raise ConfigHarnessError(f"schema block is not valid JSON: {exc}") from None
    params: dict[str, Any] = {}
    for name, pattern in _PARAM_RE.items():
        found = pattern.search(fixed)
        if found is None:
            raise ConfigHarnessError(f"harness.py is not a config harness: no {name}")
        try:
            value = ast.literal_eval(found.group(1))
            if not isinstance(value, str):
                raise ValueError(name)
            params[name.lower()] = value
        except (ValueError, SyntaxError):
            raise ConfigHarnessError(f"harness.py is not a config harness: bad {name}") from None
    return {**params, "schema": schema, "config": config, "fixed": fixed}


def _canonical_fixed(params: Mapping[str, Any]) -> str:
    rendered = render_harness(params["entrypoint"], params["entry_path"], params["entry_base"],
                              params["schema"], {})
    return split_harness(rendered)[0]


def _first_difference(a: str, b: str) -> str:
    for number, (left, right) in enumerate(zip(a.splitlines(), b.splitlines()), start=1):
        if left != right:
            return f"line {number}: {right.strip()[:120]!r} (expected {left.strip()[:120]!r})"
    return "line count differs"


def _read_harness(directory: Path) -> dict[str, Any]:
    path = Path(directory) / "harness.py"
    if not path.is_file():
        raise ConfigHarnessError(f"no harness.py in {directory}")
    params = parse_harness(path.read_text(encoding="utf-8"))
    if params["fixed"] != _canonical_fixed(params):
        raise ConfigHarnessError(f"{path}: code outside the config block differs from the generated "
                                 f"template ({_first_difference(_canonical_fixed(params), params['fixed'])})")
    return params


def _effective_config(directory: Path, params: Mapping[str, Any]) -> Any:
    sibling = Path(directory) / "config.json"
    if not sibling.is_file():
        return params["config"]
    try:
        config = json.loads(sibling.read_text(encoding="utf-8"))
    except ValueError as exc:
        raise ConfigHarnessError(f"{sibling} is not valid JSON: {exc}") from None
    if config != params["config"]:
        raise ConfigHarnessError(f"{sibling} differs from the config block in harness.py; run "
                                 f"`meta-harness adapt sync {directory}`")
    return config


def validate_candidate(candidate_dir: Path | str, seed_dir: Path | str,
                       schema: Mapping[str, Any] | None = None) -> dict[str, Any]:
    """Refuse a candidate unless only its config changed and that config satisfies the schema.

    harness.py must equal the seed's generated template outside the config block (same entrypoint,
    entry path and embedded schema, no added code). `schema` defaults to the seed's embedded
    schema; frozen keys are compared with the seed's config. Returns the candidate's config."""
    seed = _read_harness(Path(seed_dir))
    candidate = parse_harness((Path(candidate_dir) / "harness.py").read_text(encoding="utf-8")) \
        if (Path(candidate_dir) / "harness.py").is_file() else None
    if candidate is None:
        raise ConfigHarnessError(f"no harness.py in {candidate_dir}")
    if candidate["fixed"] != seed["fixed"]:
        raise ConfigHarnessError("config-only search: harness.py may not change outside the config "
                                 f"block ({_first_difference(seed['fixed'], candidate['fixed'])})")
    config = _effective_config(Path(candidate_dir), candidate)
    schema = seed["schema"] if schema is None else schema
    errors = validate_config(config, schema, seed_config=_effective_config(Path(seed_dir), seed))
    if errors:
        shown = "; ".join(errors[:8]) + (f"; and {len(errors) - 8} more" if len(errors) > 8 else "")
        raise ConfigHarnessError(f"config violates the schema: {shown}")
    return config


def _load_json(path: Path, what: str) -> Any:
    try:
        return json.loads(Path(path).read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise ConfigHarnessError(f"{what} not found: {path}") from None
    except ValueError as exc:
        raise ConfigHarnessError(f"{what} {path} is not valid JSON: {exc}") from None


def init_seed(entrypoint: str, config_path: Path | str, out: Path | str,
              schema_path: Path | str | None = None, entry_dir: Path | str = ".",
              check_import: bool = True) -> Path:
    """Scaffold `out/harness.py`, `out/config.json` and `out/schema.json`. Without a schema file
    the schema is permissive ({"type": "object"}). The seed config must satisfy the schema."""
    config = _load_json(Path(config_path), "config")
    schema = _load_json(Path(schema_path), "schema") if schema_path else {"type": "object"}
    check_schema(schema)
    errors = validate_config(config, schema)
    if errors:
        raise ConfigHarnessError("the seed config violates its own schema: " + "; ".join(errors[:8]))
    entry_path, entry_base = entry_location(Path(entry_dir))
    text = render_harness(entrypoint, entry_path, entry_base, schema, config)
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "harness.py").write_text(text, encoding="utf-8", newline="\n")
    (out / "config.json").write_text(_dump(config) + "\n", encoding="utf-8", newline="\n")
    (out / "schema.json").write_text(_dump(schema) + "\n", encoding="utf-8", newline="\n")
    if check_import:
        params = parse_harness(text)
        load_entrypoint(params)
    return out / "harness.py"


def sync_seed(seed_dir: Path | str, schema_path: Path | str | None = None) -> Path:
    """Re-render harness.py from the seed's (hand-edited) config.json and schema.json."""
    seed_dir = Path(seed_dir)
    params = parse_harness((seed_dir / "harness.py").read_text(encoding="utf-8"))
    config = _load_json(seed_dir / "config.json", "config")
    schema_file = Path(schema_path) if schema_path else seed_dir / "schema.json"
    schema = _load_json(schema_file, "schema") if schema_file.is_file() else params["schema"]
    errors = validate_config(config, schema)
    if errors:
        raise ConfigHarnessError("config.json violates the schema: " + "; ".join(errors[:8]))
    text = render_harness(params["entrypoint"], params["entry_path"], params["entry_base"], schema, config)
    (seed_dir / "harness.py").write_text(text, encoding="utf-8", newline="\n")
    if not (seed_dir / "schema.json").is_file() or schema_path:
        (seed_dir / "schema.json").write_text(_dump(schema) + "\n", encoding="utf-8", newline="\n")
    return seed_dir / "harness.py"


def load_entrypoint(params: Mapping[str, Any]) -> Any:
    """Import the entrypoint named by parsed harness params (as the generated harness does)."""
    import importlib
    import sys

    folder = PACKAGE_ROOT / params["entry_path"] if params["entry_base"] == "package" \
        else Path(params["entry_path"])
    if str(folder) not in sys.path:
        sys.path.insert(0, str(folder))
    module_name, _, function = params["entrypoint"].partition(":")
    try:
        target = getattr(importlib.import_module(module_name), function)
    except (ImportError, AttributeError) as exc:
        raise ConfigHarnessError(f"cannot import entrypoint {params['entrypoint']!r} from {folder}: {exc}") from None
    if not callable(target):
        raise ConfigHarnessError(f"entrypoint {params['entrypoint']!r} is not callable")
    return target


def copy_seed(seed_dir: Path | str, out: Path | str) -> Path:
    """Copy a seed directory (harness.py, config.json, schema.json) elsewhere."""
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    for name in ("harness.py", "config.json", "schema.json"):
        if (Path(seed_dir) / name).is_file():
            shutil.copy2(Path(seed_dir) / name, out / name)
    return out / "harness.py"


__all__ = ["ConfigHarnessError", "TEMPLATE", "copy_seed", "entry_location", "init_seed",
           "load_entrypoint", "parse_harness", "render_harness", "split_harness", "sync_seed",
           "validate_candidate"]
